-- Catalogo canonico de paises (ticket: contacts.country sin normalizar).
-- SOLO crea las tablas e inserta el seed. NO toca contacts ni ninguna otra tabla.
-- Idempotente: se puede repetir sin efecto.
--
-- `name` es el endonimo (nombre en el idioma del propio pais) porque ese valor se
-- imprime en la variable {{country}} de las plantillas de WhatsApp. Los 30 nombres
-- de CALLING_CODE_TO_COUNTRY (src/constants/country_names.py) se reproducen literales.
-- `country_aliases.alias` es la clave YA normalizada: minusculas, sin acentos,
-- espacios colapsados. Quien consulte debe normalizar igual antes de buscar.

BEGIN;

CREATE TABLE IF NOT EXISTS public.countries (
    iso2          char(2)     PRIMARY KEY,
    name          text        NOT NULL UNIQUE,
    calling_codes text[]      NOT NULL DEFAULT '{}',
    created_at    timestamptz NOT NULL DEFAULT now()
);

COMMENT ON TABLE  public.countries IS 'Catalogo canonico de paises. name = endonimo, usado en la variable {{country}}.';
COMMENT ON COLUMN public.countries.calling_codes IS 'Codigos E.164 sin +. Sin solapes: el bare 1 es US y el 61 AU, como en CALLING_CODE_TO_COUNTRY.';

CREATE TABLE IF NOT EXISTS public.country_aliases (
    alias      text        PRIMARY KEY,
    iso2       char(2)     NOT NULL REFERENCES public.countries(iso2) ON UPDATE CASCADE,
    created_at timestamptz NOT NULL DEFAULT now()
);

COMMENT ON TABLE public.country_aliases IS 'Variantes aceptadas -> iso2. alias ya normalizado (minusculas, sin acentos, sin espacios extra).';

CREATE INDEX IF NOT EXISTS country_aliases_iso2_idx ON public.country_aliases (iso2);

